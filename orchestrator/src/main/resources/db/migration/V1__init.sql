create table seed_topic (
    id          bigint generated by default as identity primary key,
    title       varchar(300)             not null,
    notes       varchar(4000),
    format      varchar(40)              not null,
    language    varchar(10)              not null,
    status      varchar(20)              not null,
    created_at  timestamp with time zone not null
);

create table run (
    id              bigint generated by default as identity primary key,
    seed_topic_id   bigint references seed_topic (id),
    topic_title     varchar(300)             not null,
    format          varchar(40)              not null,
    language        varchar(10)              not null,
    profile         varchar(60)              not null,
    state           varchar(30)              not null,
    status          varchar(20)              not null,
    status_reason   varchar(2000),
    target_seconds  integer                  not null,
    cache_salt      integer                  not null default 0,
    created_at      timestamp with time zone not null,
    updated_at      timestamp with time zone not null,
    started_at      timestamp with time zone,
    finished_at     timestamp with time zone
);

create index idx_run_status on run (status);

create table stage_execution (
    id              bigint generated by default as identity primary key,
    run_id          bigint                   not null references run (id),
    stage           varchar(30)              not null,
    status          varchar(20)              not null,
    provider        varchar(120),
    prompt_version  varchar(40),
    input_tokens    bigint                   not null default 0,
    output_tokens   bigint                   not null default 0,
    cost_usd        numeric(10, 4)           not null default 0,
    error           varchar(4000),
    started_at      timestamp with time zone not null,
    finished_at     timestamp with time zone,
    duration_ms     bigint
);

create index idx_stage_execution_run on stage_execution (run_id);

create table cost_entry (
    id             bigint generated by default as identity primary key,
    run_id         bigint references run (id),
    stage          varchar(30),
    provider       varchar(120)             not null,
    input_tokens   bigint                   not null default 0,
    output_tokens  bigint                   not null default 0,
    cost_usd       numeric(10, 4)           not null default 0,
    created_at     timestamp with time zone not null
);

create index idx_cost_entry_run on cost_entry (run_id);

create table app_setting (
    setting_key    varchar(100)             primary key,
    setting_value  varchar(2000)            not null,
    updated_at     timestamp with time zone not null
);
