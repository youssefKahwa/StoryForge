create table revision (
    id          bigint generated by default as identity primary key,
    run_id      bigint                   not null references run (id),
    kind        varchar(20)              not null,
    target      varchar(60)              not null,
    at_sec      double precision,
    note        varchar(2000)            not null,
    status      varchar(20)              not null,
    result      varchar(4000),
    created_at  timestamp with time zone not null,
    updated_at  timestamp with time zone not null
);

create index revision_run_idx on revision (run_id);

alter table inspiration add column auto_start boolean default false not null;
alter table inspiration add column owner_notes varchar(2000);
