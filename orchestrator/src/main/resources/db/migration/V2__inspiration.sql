create table inspiration (
    id           bigint generated by default as identity primary key,
    status       varchar(20)              not null,
    urls         varchar(2000)            not null,
    pasted_text  varchar(200000),
    error        varchar(4000),
    created_at   timestamp with time zone not null,
    updated_at   timestamp with time zone not null
);

alter table run add column inspiration_id bigint references inspiration (id);
alter table run add column angle varchar(2000);
alter table run add column voice varchar(60);
